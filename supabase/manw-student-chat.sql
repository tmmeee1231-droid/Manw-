-- MANW student chat: run this once in Supabase SQL Editor.
create table if not exists public.subject_chat_messages (
  id bigint generated by default as identity primary key,
  subject text not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  sender_name text not null default 'طالب MANW',
  body text not null check (char_length(body) between 1 and 1000),
  created_at timestamptz not null default now()
);

create index if not exists subject_chat_messages_subject_created_idx
  on public.subject_chat_messages (subject, created_at);

alter table public.subject_chat_messages enable row level security;

drop policy if exists "Students can read recent subject messages" on public.subject_chat_messages;
create policy "Students can read recent subject messages"
  on public.subject_chat_messages for select to authenticated
  using (created_at >= now() - interval '5 hours');

drop policy if exists "Students can send as themselves" on public.subject_chat_messages;
create policy "Students can send as themselves"
  on public.subject_chat_messages for insert to authenticated
  with check (
    auth.uid() = user_id
    and char_length(body) between 1 and 1000
    and created_at >= now() - interval '1 minute'
  );

drop policy if exists "Students can delete expired messages" on public.subject_chat_messages;
create policy "Students can delete expired messages"
  on public.subject_chat_messages for delete to authenticated
  using (created_at < now() - interval '5 hours');

grant select, insert, delete on public.subject_chat_messages to authenticated;
grant usage, select on sequence public.subject_chat_messages_id_seq to authenticated;

-- Server-side cleanup: remove expired messages every minute.
create extension if not exists pg_cron with schema extensions;
do $$
begin
  if not exists (select 1 from cron.job where jobname = 'manw-chat-cleanup') then
    perform cron.schedule(
      'manw-chat-cleanup',
      '* * * * *',
      $job$delete from public.subject_chat_messages where created_at < now() - interval '5 hours';$job$
    );
  end if;
end
$$;
