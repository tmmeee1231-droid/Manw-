create table if not exists public.student_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  phone text not null default '',
  role text not null default 'student' check (role in ('student','admin')),
  is_banned boolean not null default false,
  created_at timestamptz not null default now()
);

create unique index if not exists student_profiles_full_name_ci
  on public.student_profiles (lower(full_name))
  where full_name <> '';

create or replace function public.manw_create_student_profile()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.student_profiles (user_id, full_name, phone)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', ''),
    coalesce(new.raw_user_meta_data ->> 'phone', '')
  )
  on conflict (user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists manw_auth_user_created on auth.users;
create trigger manw_auth_user_created
  after insert on auth.users
  for each row execute procedure public.manw_create_student_profile();

create table if not exists public.subject_chat_messages (
  id bigint generated by default as identity primary key,
  subject text not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  sender_name text not null default '',
  body text not null check (char_length(body) between 1 and 3000),
  created_at timestamptz not null default now()
);

create index if not exists subject_chat_messages_subject_created
  on public.subject_chat_messages (subject, created_at);

alter table public.student_profiles enable row level security;
alter table public.subject_chat_messages enable row level security;

drop policy if exists "students read own profile or admins read all" on public.student_profiles;
create policy "students read own profile or admins read all"
on public.student_profiles for select to authenticated
using (
  user_id = auth.uid()
  or exists (
    select 1 from public.student_profiles me
    where me.user_id = auth.uid() and me.role = 'admin'
  )
);

drop policy if exists "students update own basic profile" on public.student_profiles;
create policy "students update own basic profile"
on public.student_profiles for update to authenticated
using (user_id = auth.uid())
with check (user_id = auth.uid());

revoke all on public.student_profiles from anon, authenticated;
grant select on public.student_profiles to authenticated;
grant update (full_name, phone) on public.student_profiles to authenticated;

drop policy if exists "signed in students read subject chat" on public.subject_chat_messages;
create policy "signed in students read subject chat"
on public.subject_chat_messages for select to authenticated
using (true);

drop policy if exists "students send as themselves" on public.subject_chat_messages;
create policy "students send as themselves"
on public.subject_chat_messages for insert to authenticated
with check (user_id = auth.uid());

drop policy if exists "students clean expired chat messages" on public.subject_chat_messages;
create policy "students clean expired chat messages"
on public.subject_chat_messages for delete to authenticated
using (created_at < now() - interval '5 hours');

grant select, insert, delete on public.subject_chat_messages to authenticated;
grant usage, select on sequence public.subject_chat_messages_id_seq to authenticated;

create or replace function public.admin_set_student_ban(target_user uuid, ban_status boolean)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not exists (
    select 1 from public.student_profiles
    where user_id = auth.uid() and role = 'admin'
  ) then
    raise exception 'غير مسموح: هذه العملية للإدارة فقط';
  end if;

  update public.student_profiles
  set is_banned = ban_status
  where user_id = target_user and role <> 'admin';
end;
$$;

revoke all on function public.admin_set_student_ban(uuid, boolean) from public, anon;
grant execute on function public.admin_set_student_ban(uuid, boolean) to authenticated;
